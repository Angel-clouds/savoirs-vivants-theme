<h2 class="wp-block-heading">Notre histoire</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>En 2023, dans un contexte de transformation de l'emploi industriel et de chômage de masse, notamment pour les populations les moins qualifiées, des bénévoles issus de différentes villes d'Alsace se sont réunis pour proposer des alternatives aux enjeux de notre époque : décarbonation des industries, transition écologique et numérique, vieillissement des populations.</p>
<!-- /wp:paragraph -->
<!-- wp:quote -->
<blockquote class="wp-block-quote">
<!-- wp:paragraph -->
<p>Les fondateurs se sont donnés pour mission de faire de « Savoirs Vivants » un regroupement de personnes physiques ou morales qui partagent les valeurs liées au droit au savoir, à l'éducation, à l'émancipation des hommes et des femmes libres capables de maîtriser leur devenir dans une société en transition.</p>
<!-- /wp:paragraph -->
<cite>Extrait des statuts de l'association</cite></blockquote>
<!-- /wp:quote -->
<!-- wp:paragraph -->
<p>En 2025, l'association est passée de 2 à 5 salariés et s'est installée dans un grand espace de bureaux au sein de l'IUT de Haguenau. Elle se professionnalise, tout en gardant vivant son fonctionnement démocratique et sa culture de la délibération.</p>
